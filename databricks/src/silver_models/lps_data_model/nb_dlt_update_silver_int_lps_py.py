    comment = "Table which replicates what System Support and Mortgage Originations used to do in the PMAP spreadsheet to log cloned products. The clones are used for specific circumstances and are immediately withdrawn once allocated to an account (they might be reopened briefly if the same specific circumstance recurs), or they may just be created for illustration purposes and never allocated to an account. Foreign keys are NOVALIDATE as some products were not able to be migrated that are listed in here."
