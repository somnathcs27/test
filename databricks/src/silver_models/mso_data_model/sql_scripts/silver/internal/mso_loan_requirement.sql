SELECT
	CAST(UPPER(lr.LoanRequirementId) AS STRING) AS LOAN_REQUIREMENT_ID,
	CAST(UPPER(lr.CaseId) AS STRING) AS CASE_ID,
	CAST(lr.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
	CAST(lr.IndexValuationDate AS TIMESTAMP) AS INDEX_VALUATION_DATETIME,
	CAST(lr.OriginalDateOfPurchase AS TIMESTAMP) AS ORIGINAL_PURCHASE_DATETIME,
	CAST(lr.ApplicationType AS STRING) AS APPLICATION_TYPE,
	CAST(lr.PropertyPurpose AS STRING) AS PROPERTY_PURPOSE,
	CAST(lr.PropertyOwnership AS STRING) AS PROPERTY_OWNERSHIP,
	CAST(lr.LettingType AS STRING) AS LETTING_TYPE,
	CAST(lr.TenancyLength AS STRING) AS TENANCY_LENGTH,
	CAST(lr.RepaymentMethod AS STRING) AS REPAYMENT_METHOD,
	CAST(lr.Currency AS STRING) AS CURRENCY,
	CAST(lr.CurrentEstimatedValue AS DECIMAL(10,2)) AS CURRENT_ESTIMATED_VALUE,
	CAST(lr.PurchasePrice AS DECIMAL(10,2)) AS PURCHASE_PRICE,
	CAST(lr.TotalLoanAmount AS DECIMAL(10,2)) AS TOTAL_LOAN_AMOUNT,
	CAST(lr.InterestOnlyAmount AS DECIMAL(10,2)) AS INTEREST_ONLY_AMOUNT,
	CAST(lr.MortgageTermMonths AS INT) AS MORTGAGE_TERM_MONTHS,
	CAST(lr.UnencumberedPropertyValue AS DECIMAL(11,2)) AS UNENCUMBERED_PROPERTY_VALUE,
	CAST(lr.UnencumberedPropertyCount AS INT) AS UNENCUMBERED_PROPERTY_COUNT,
	CAST(lr.FullMarketValue AS DECIMAL(10,2)) AS FULL_MARKET_VALUE,
	CAST(lr.EquityShareTermMonths AS INT) AS EQUITY_SHARE_TERM_MONTHS,
	CAST(lr.ProjectedRentalIncome AS DECIMAL(10,2)) AS PROJECTED_RENTAL_INCOME,
	CAST(lr.AmountTransferredFromAnotherLender AS DECIMAL(10,2)) AS AMOUNT_TRANSFERRED_FROM_ANOTHER_LENDER,
	CAST(lr.NumberOfExistingHolidayLets AS SMALLINT) AS NUMBER_OF_EXISTING_HOLIDAY_LETS,
	CAST(lr.BuyToLetTotalPortfolio AS DECIMAL(12,2)) AS BUY_TO_LET_PORTFOLIO_TOTAL_VALUE,
	CAST(lr.FamilyOccupancy AS TINYINT) AS FAMILY_OCCUPANCY,
	CAST(lr.PropertyInPreferentialArea AS TINYINT) AS PROPERTY_IN_PREFERENTIAL_AREA,
	CAST(lr.GuaranteeShareScheme AS STRING) AS GUARANTEE_SHARE_SCHEME,
	CAST(lr.EquityShareScheme AS STRING) AS EQUITY_SHARE_SCHEME,
	CAST(lr.TransferOfEquity AS STRING) AS TRANSFER_OF_EQUITY,
	CAST(lr.HasPortfolioOfExistingMortgages AS TINYINT) AS HAS_PORTFOLIO_OF_EXISTING_MORTGAGES,
	CAST(lr.OptInToBtlTopSlicing AS TINYINT) AS OPT_IN_TO_BTL_TOP_SLICING,
	CAST(lr.OwnOtherLetProperties AS TINYINT) AS OWN_OTHER_LET_PROPERTIES,
	CAST(lr.InheritedGiftedProperty AS TINYINT) AS IS_INHERITED_GIFT_PROPERTY,
	CAST(lr.IsNewBuild AS TINYINT) AS IS_NEW_BUILD,
	CAST(lr.ApplicantsOwnOtherProperty AS TINYINT) AS APPLICANTS_OWN_OTHER_PROPERTY,
	CAST(lr.ApplicantsFirstTimeLandlords AS TINYINT) AS APPLICANTS_FIRST_TIME_LANDLORDS,
	CAST(lr.IntendedFamilyOccupancy AS TINYINT) AS IS_FAMILY_OCCUPANCY_INTENDED,
	CAST(lr.PreviousFamilyOccupancy AS TINYINT) AS HAS_PREVIOUS_FAMILY_OCCUPANCY,
	CAST(lr.HpiChallenged AS TINYINT) AS IS_HPI_CHALLENGED,
	CAST(lr.HasPropertyChanged AS TINYINT) AS HAS_PROPERTY_CHANGED,
	CAST(lr.RetirementInterestOnly AS TINYINT) AS IS_RETIREMENT_INTEREST_ONLY,
	CAST(lr.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
	CAST(lr.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
	CAST(lr.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
	CAST(lr.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
	CAST(lr.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME
FROM {env_var}_catalog.bronze_mso_int.loan_requirement lr
WHERE lr.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1;