SELECT
  CAST(UPPER(spv.SelectedProductValueId) AS STRING) AS SELECTED_PRODUCT_VALUE_ID,
  CAST(UPPER(spv.CaseId) AS STRING) AS CASE_ID,
  CAST(UPPER(spv.ProductId) AS STRING) AS PRODUCT_ID,
  CAST(spv.DateInitialRateEnds AS TIMESTAMP) AS INITIAL_RATE_END_DATETIME,
  CAST(spv.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
  CAST(spv.ExistingProductCode AS INT) AS EXISTING_PRODUCT_CODE,
  CAST(spv.ProductCode AS INT) AS PRODUCT_CODE,
  CAST(spv.ProductDescription AS STRING) AS PRODUCT_DESCRIPTION,
  CAST(spv.ProductType AS STRING) AS PRODUCT_TYPE,
  CAST(spv.LoanPartType AS STRING) AS LOAN_PART_TYPE,
  CAST(spv.AccountRegulation AS STRING) AS ACCOUNT_REGULATION,
  CAST(spv.BeneficialRatePeriod AS STRING) AS BENEFICIAL_RATE_PERIOD,
  CAST(spv.ReversionRateType AS STRING) AS REVERSION_RATE_TYPE,
  CAST(spv.ReversionRate AS DECIMAL(10,3)) AS REVERSION_RATE,
  CAST(spv.ExistingMortgageAccountReference AS STRING) AS EXISTING_MORTGAGE_ACCOUNT_REFERENCE,
  CAST(spv.SplitFromAccountReference AS STRING) AS SPLIT_FROM_ACCOUNT_REFERENCE,
  CAST(spv.ForDebtConsolidation AS INT) AS FOR_DEBT_CONSOLIDATION,
  CAST(spv.ExistingTermInMonths AS INT) AS EXISTING_TERM_IN_MONTHS,
  CAST(spv.TermInMonths AS INT) AS TERM_IN_MONTHS,
  CAST(spv.ExistingCapitalAmount AS DECIMAL(10,2)) AS EXISTING_CAPITAL_AMOUNT,
  CAST(spv.CapitalAmount AS DECIMAL(10,2)) AS CAPITAL_AMOUNT,
  CAST(spv.ExistingInterestOnlyAmount AS DECIMAL(10,2)) AS EXISTING_INTEREST_ONLY_AMOUNT,
  CAST(spv.InterestOnlyAmount AS DECIMAL(10,2)) AS INTEREST_ONLY_AMOUNT,
  CAST(spv.InitialInterestRate AS DECIMAL(10,3)) AS INITIAL_INTEREST_RATE,
  CAST(spv.InitialMonthlyRepayment AS DECIMAL(10,2)) AS INITIAL_MONTHLY_REPAYMENT,
  CAST(spv.Apr AS DECIMAL(10,3)) AS APR,
  CAST(spv.MaximumLtv AS DECIMAL(10,3)) AS MAXIMUM_LTV,
  CAST(spv.CappedInterestRate AS TINYINT) AS HAS_CAPPED_INTEREST_RATE,
  CAST(spv.CanSwitchProduct AS TINYINT) AS CAN_SWITCH_PRODUCT,
  CAST(spv.CanChangeRepaymentBasis AS TINYINT) AS CAN_CHANGE_REPAYMENT_BASIS,
  CAST(spv.CanChangeTerm AS TINYINT) AS CAN_CHANGE_TERM,
  CAST(spv.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
  CAST(spv.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
  CAST(spv.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
  CAST(spv.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
  CAST(spv.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME
FROM {env_var}_catalog.bronze_mso_int.selected_product_value spv
WHERE spv.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1
