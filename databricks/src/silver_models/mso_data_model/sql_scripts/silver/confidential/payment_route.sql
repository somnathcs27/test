SELECT
  CAST(UPPER(pr.PaymentRouteId) AS STRING) AS PAYMENT_ROUTE_ID,
  CAST(UPPER(pr.ParentId) AS STRING) AS PARENT_DISTRIBUTOR_ID,
  CAST(UPPER(pr.Name) AS STRING) AS PAYMENT_ROUTE_NAME,
  CAST(pr.PaymentRouteType AS STRING) AS PAYMENT_ROUTE_TYPE,
  CAST(pr.PaymentRouteCode AS STRING) AS PAYMENT_ROUTE_CODE,
  CAST(UPPER(pr.BuildingName) AS STRING) AS BUILDING_NAMe,
  CAST(UPPER(pr.BuildingNumber) AS STRING) AS BUILDING_NUMBER,
  CAST(UPPER(pr.Flat) AS STRING) AS FLAT,
  CAST(UPPER(pr.Street) AS STRING) AS STREET,
  CAST(UPPER(pr.District) AS STRING) AS DISTRICT,
  CAST(UPPER(pr.Town) AS STRING) AS TOWN,
  CAST(UPPER(pr.County) AS STRING) AS COUNTY,
  CAST(UPPER(pr.Postcode) AS STRING) AS POSTCODE,
  CAST(pr.RegistrationNumber AS BIGINT) AS REGISTRATION_NUMBER,
  CAST(pr.AgencyNumber AS STRING) AS AGENCY_NUMBER,
  CAST(pr.ExternalReference AS STRING) AS EXTERNAL_REFERENCE,
  CAST(pr.IsPaidProcFee AS TINYINT) AS IS_PAID_PROCURATION_FEE,
  CAST(pr.IsActive AS TINYINT) AS IS_ACTIVE,
  CAST(pr.CreatedDate AS TIMESTAMP) AS CREATED_DATETIME,
  CAST(pr.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
  CAST(pr.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
  CAST(pr.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
  CAST(pr.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
  CAST(pr.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
  CAST(pr.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME
FROM {env_var}_catalog.bronze_mso_con.payment_route pr
WHERE pr.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1