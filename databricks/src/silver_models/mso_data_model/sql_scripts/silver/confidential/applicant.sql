SELECT
  CAST(UPPER(a.ApplicantId) AS STRING) AS APPLICANT_ID,
  CAST(UPPER(a.CaseId) AS STRING) AS CASE_ID,
  -- TRY_CAST because of crap UAT data. Numeric in prod.
  CAST(a.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
  TRY_CAST(a.LenderCustomerId AS BIGINT) AS LENDER_CUSTOMER_ID,
  -- Renamed Index to APPLICANT_INDEX as INDEX is a reserved keyword
  -- Renaming the next two columns to have a more descriptive name
  CAST(a.DependentChildren AS SMALLINT) AS NUMBER_OF_DEPENDENT_CHILDREN,
  CAST(a.DependentAdults AS SMALLINT) AS NUMBER_OF_DEPENDENT_ADULTS,
  CAST(a.RetirementAge AS SMALLINT) AS RETIREMENT_AGE,
  CAST(a.NetMonthlyIncome AS DECIMAL(12, 2)) AS NET_MONTHLY_INCOME,
  CAST(a.MainEmploymentStatus AS STRING) AS MAIN_EMPLOYMENT_STATUS,
  CAST(a.Index AS SMALLINT) AS APPLICANT_INDEX,
  CAST(a.ApplicantType AS STRING) AS APPLICANT_TYPE,
  CAST(a.DateOfBirth AS DATE) AS APPLICANT_DATE_OF_BIRTH,
  CAST(UPPER(a.Title) AS STRING) AS APPLICANT_TITLE,
  CAST(UPPER(a.Forename) AS STRING) AS APPLICANT_FORENAME,
  CAST(UPPER(a.MiddleName) AS STRING) AS APPLICANT_MIDDLE_NAME,
  CAST(UPPER(a.Surname) AS STRING) AS APPLICANT_SURNAME,
  CAST(UPPER(a.PreviousTitle) AS STRING) AS APPLICANT_PREVIOUS_TITLE,
  CAST(UPPER(a.PreviousForename) AS STRING) AS APPLICANT_PREVIOUS_FORENAME,
  CAST(UPPER(a.PreviousMiddleName) AS STRING) AS APPLICANT_PREVIOUS_MIDDLE_NAME,
  CAST(UPPER(a.PreviousSurname) AS STRING) AS APPLICANT_PREVIOUS_SURNAME,
  CAST(a.Nationality AS STRING) AS APPLICANT_NATIONALITY_CATEGORY,
  CAST(a.CountryOfNationality AS STRING) AS APPLICANT_COUNTRY_OF_NATIONALITY,
  CAST(a.CountryOfSecondNationality AS STRING) AS APPLICANT_COUNTRY_OF_SECOND_NATIONALITY,
  CAST(a.HomeTelephone AS STRING) AS APPLICANT_HOME_TELEPHONE,
  CAST(a.MobileTelephone AS STRING) AS APPLICANT_MOBILE_TELEPHONE,
  CAST(a.Email AS STRING) AS APPLICANT_EMAIL_ADDRESS,
  CAST(a.Gender AS STRING) AS APPLICANT_GENDER,
  CAST(a.MaritalStatus AS STRING) AS APPLICANT_MARITAL_STATUS,
  CAST(a.Presence AS STRING) AS PRESENCE,
  CAST(a.BorrowerSector AS STRING) AS BORROWER_SECTOR,
  CAST(UPPER(a.ElectronicId) AS STRING) AS ELECTRONIC_ID,
  CAST(a.FutureTaxRateBand AS STRING) AS FUTURE_TAX_RATE_BAND,
  CAST(a.TransferOfEquityStatus AS STRING) AS TRANSFER_OF_EQUITY_STATUS,
  CAST(a.PermanentUkResidence AS TINYINT) AS IS_PERMANENT_UK_RESIDENT,
  CAST(a.IsRetired AS TINYINT) AS IS_RETIRED,
  CAST(a.NameChanged AS TINYINT) AS HAS_NAME_CHANGED,
  CAST(a.Tier1Visa AS TINYINT) AS HAS_TIER_1_VISA,
  CAST(a.IndefiniteLeave AS TINYINT) AS HAS_INDEFINITE_LEAVE_TO_REMAIN,
  CAST(a.HasDualNationality AS TINYINT) AS HAS_DUAL_NATIONALITY,
  CAST(a.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
  CAST(a.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
  CAST(a.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
  CAST(a.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
  CAST(a.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME 
FROM {env_var}_catalog.bronze_mso_con.applicant a
WHERE a.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1