SELECT
  CAST(UPPER(i.IntermediaryId) AS STRING) AS INTERMEDIARY_ID,
  CAST(UPPER(i.FirmId) AS STRING) AS FIRM_ID,
  CAST(UPPER(i.TradingAddressId) AS STRING) AS TRADING_ADDRESS_ID,
  CAST(UPPER(i.Title) AS STRING) AS INTERMEDIARY_TITLE,
  CAST(UPPER(i.Forename) AS STRING) AS INTERMEDIARY_FORENAME,
  CAST(UPPER(i.Surname) AS STRING) AS INTERMEDIARY_SURNAME,
  CAST(i.DateOfBirth AS DATE) AS INTERMEDIARY_DATE_OF_BIRTH,
  CAST(i.EmailAddress AS STRING) AS INTERMEDIARY_EMAIL_ADDRESS,
  CAST(i.Mobile AS STRING) AS INTERMEDIARY_MOBILE_TELEPGONE,
  CAST(i.Telephone AS STRING) AS INTERMEDIARY_TELEPHONE,
  CAST(i.BDMRelationship AS STRING) AS BDM_RELATIONSHIP,
  CAST(i.Roles AS STRING) AS INTERMEDIARY_ROLES,
  CAST(UPPER(i.BuildingName) AS STRING) AS BUILDING_NAME,
  CAST(UPPER(i.BuildingNumber) AS STRING) AS BUILDING_NUMBER,
  CAST(UPPER(i.Flat) AS STRING) AS FLAT,
  CAST(UPPER(i.Street) AS STRING) AS STREET,
  CAST(UPPER(i.District) AS STRING) AS DISTRICT,
  CAST(UPPER(i.Town) AS STRING) AS TOWN,
  CAST(UPPER(i.County) AS STRING) AS COUNTY,
  CAST(UPPER(i.Postcode) AS STRING) AS POSTCODE,
  CAST(i.ReferenceNumber AS STRING) AS REFERENCE_NUMBER,
  CAST(i.Bdm AS STRING) AS BUSINESS_DEVELOPMENT_MANAGER_CODE,
  CAST(i.InactiveReason AS STRING) AS INACTIVE_REASON,
  CAST(i.ExternalReference AS STRING) AS EXTERNAL_REFERENCE,
  CAST(i.HasSMSNotifications AS TINYINT) AS HAS_SMS_NOTIFICATIONS,
  CAST(i.IsActive AS TINYINT) AS IS_ACTIVE,
  CAST(i.Islocked AS TINYINT) AS IS_LOCKED,
  CAST(i.IsPrincipal AS TINYINT) AS IS_PRINCIPAL,
  CAST(i.HasMarketingPreference AS TINYINT) AS HAS_MARKETING_PREFERENCES,
  CAST(i.AreAdminsSentNotifications AS TINYINT) AS ARE_ADMINS_SENT_NOTIFICATIONS,
  CAST(i.CanAllAdminsAccessCases AS TINYINT) AS CAN_ALL_ADMINS_ACCESS_CASES,
  CAST(i.CreatedDate AS TIMESTAMP) AS CREATED_DATETIME,
  CAST(i.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
  CAST(i.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
  CAST(i.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
  CAST(i.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
  CAST(i.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
  CAST(i.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME
FROM {env_var}_catalog.bronze_mso_con.intermediary i
WHERE i.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1