SELECT
	CAST(UPPER(vrs.ValuationReportStatusHistoryId) AS STRING) AS VALUATION_REPORT_STATUS_HISTORY_ID,
	CAST(UPPER(vrs.ValuationReportId) AS STRING) AS VALUATION_REPORT_ID,
	CAST(vrs.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
	CAST(vrs.CreatedDate AS TIMESTAMP) AS CREATED_DATETIME,
	CAST(vrs.CurrentState AS STRING) AS CURRENT_STATE,
	CAST(vrs.UpdatedByName AS STRING) AS UPDATED_BY_NAME,
	CAST(vrs.Notes AS STRING) AS NOTES,
	CAST(vrs.ValuerName AS STRING) AS VALUER_NAME,
	CAST(vrs.ValuerFirmName AS STRING) AS VALUER_FIRM_NAME,
	CAST(vrs.ValuerEmailAddress AS STRING) AS VALUER_EMAIL_ADDRESS,
	CAST(vrs.ValuerFirmTelephoneNumber AS STRING) AS VALUER_FIRM_TELEPHONE_NUMBER,
	CAST(vrs.ValuerFirmBuildingNo AS STRING) AS VALUER_FIRM_BUILDING_NO,
	CAST(vrs.ValuerFirmBuildingName AS STRING) AS VALUER_FIRM_BUILDING_NAME,
	CAST(vrs.ValuerFirmFlatIdentifier AS STRING) AS VALUER_FIRM_FLAT_IDENTIFIER,
	CAST(vrs.ValuerFirmStreet AS STRING) AS VALUER_FIRM_STREET,
	CAST(vrs.ValuerFirmDistrict AS STRING) AS VALUER_FIRM_DISTRICT,
	CAST(vrs.ValuerFirmTown AS STRING) AS VALUER_FIRM_TOWN,
	CAST(vrs.ValuerFirmCounty AS STRING) AS VALUER_FIRM_COUNTY,
	CAST(vrs.ValuerFirmPostcode AS STRING) AS VALUER_FIRM_POSTCODE,
	CAST(vrs.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
	CAST(vrs.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
	CAST(vrs.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
	CAST(vrs.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
	CAST(vrs.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME
FROM {env_var}_catalog.bronze_mso_con.valuation_report_status_history vrs
WHERE vrs.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1
