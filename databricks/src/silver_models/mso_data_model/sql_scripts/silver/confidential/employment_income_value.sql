/*LF Note: Lots of column renames in here to make them more
explicit. Many are open to interpretation. Definitions taken
from IRESS MSO Data Dictionary.*/
SELECT
  CAST(UPPER(eiv.EmploymentIncomeValueId) AS STRING) AS EMPLOYMENT_INCOME_VALUE_ID,
  CAST(UPPER(eiv.ApplicantId) AS STRING) AS APPLICANT_ID,
  CAST(eiv.Occupation AS STRING) AS OCCUPATION,
  CAST(eiv.EmploymentStatus AS STRING) AS EMPLOYMENT_STATUS,
  CAST(eiv.EmploymentContract AS STRING) AS EMPLOYMENT_CONTRACT_TYPE,
  CAST(eiv.BasicSalary AS DECIMAL(12, 2)) BASIC_ANNUAL_SALARY,
  CAST(eiv.BonusGuaranteed AS DECIMAL(12, 2)) AS GUARANTEED_ANNUAL_BONUS_AMOUNT,
  CAST(eiv.OvertimeGuaranteed AS DECIMAL(12, 2)) AS GUARANTEED_ANNUAL_OVERTIME_AMOUNT,
  CAST(eiv.OvertimeNonGuaranteed AS DECIMAL(12, 2)) AS NON_GUARANTEED_ANNUAL_OVERTIME_AMOUNT,
  CAST(eiv.BonusNonGuaranteed AS DECIMAL(12, 2)) AS NON_GUARANTEED_ANNUAL_BONUS_AMOUNT,
  CAST(eiv.CommissionGuaranteed AS DECIMAL(12, 2)) AS GUARANTEED_ANNUAL_COMMISSION_AMOUNT,
  CAST(eiv.CommissionNonGuaranteed AS DECIMAL(12, 2)) AS NON_GUARANTEED_ANNUAL_COMMISSION_AMOUNT,
  CAST(eiv.CurrentYearNetProfit AS DECIMAL(18, 2)) AS PROJECTED_NET_PROFIT_CURRENT_YEAR,
  CAST(eiv.CurrentYearGrossProfit AS DECIMAL(18, 2)) AS PROJECTED_GROSS_PROFIT_CURRENT_YEAR,
  CAST(eiv.CurrentYearSalaryIncDividends AS DECIMAL(12, 2)) AS PROJECTED_ANNUAL_SALARY_AND_DIVIDENDS_CURRENT_YEAR,
  CAST(eiv.CurrentYearSalary AS DECIMAL(12, 2)) AS PROJECTED_ANNUAL_SALARY_CURRENT_YEAR,
  CAST(eiv.CurrentYearDividends AS DECIMAL(12, 2)) AS PROJECTED_DIVIDENDS_CURRENT_YEAR,
  CAST(eiv.PreviousYearNetProfit AS DECIMAL(18, 2)) AS NET_PROFIT_PREVIOUS_YEAR,
  CAST(eiv.PreviousYearSalaryIncDividends AS DECIMAL(12, 2)) AS ANNUAL_SALARY_AND_DIVIDENDS_PREVIOUS_YEAR,
  CAST(eiv.PreviousYearSalary AS DECIMAL(12, 2)) AS ANNUAL_SALARY_PREVIOUS_YEAR,
  CAST(eiv.PreviousYearDividends AS DECIMAL(12, 2)) AS DIVIDENDS_PREVIOUS_YEAR,
  CAST(eiv.PreviousYearTwoNetProfit AS DECIMAL(18, 2)) AS NET_PROFIT_PREVIOUS_YEAR_MINUS_ONE,
  CAST(eiv.PreviousYearTwoSalaryIncDividends AS DECIMAL(12, 2)) AS ANNUAL_SALARY_AND_DIVIDENDS_PREVIOUS_YEAR_MINUS_ONE,
  CAST(eiv.PreviousYearTwoSalary AS DECIMAL(12, 2)) AS ANNUAL_SALARY_PREVIOUS_YEAR_MINUS_ONE,
  CAST(eiv.PreviousYearTwoDividends AS DECIMAL(12, 2)) AS DIVIDENDS_PREVIOUS_YEAR_MINUS_ONE,
  CAST(eiv.PreviousYearThreeNetProfit AS DECIMAL(18, 2)) AS NET_PROFIT_PREVIOUS_YEAR_MINUS_TWO,
  CAST(eiv.PreviousYearThreeSalary AS DECIMAL(12, 2)) AS ANNUAL_SALARY_PREVIOUS_YEAR_MINUS_TWO,
  CAST(eiv.PreviousYearThreeDividends AS DECIMAL(12, 2)) AS DIVIDENDS_PREVIOUS_YEAR_MINUS_TWO,
  CAST(eiv.Allowances AS DECIMAL(12, 2)) AS TOTAL_ALLOWANCES,
  CAST(eiv.StartYear AS INT) AS EMPLOYMENT_START_YEAR,
  CAST(eiv.StartMonth AS INT) AS EMPLOYMENT_START_MONTH,
  CAST(eiv.PercentageShareholding AS DECIMAL(5, 2)) AS SHAREHOLDING_PERCENTAGE,
  CAST(eiv.TimeRemainingMonths AS INT) AS EMPLOYMENT_CONTRACT_MONTHS_REMAINING,
  CAST(eiv.TimeContractingExperienceMonths AS INT) CONTRACTING_EXPERIENCE_MONTHS,
  CAST(eiv.DailyRate AS DECIMAL(10, 2)) AS EMPLOYMENT_CONTRACT_DAILY_RATE,
  CAST(eiv.EmployerName AS STRING) AS EMPLOYER_NAME,
  CAST(eiv.ContractGapReason AS STRING) AS CONTRACT_GAP_REASON,
  CAST(eiv.ContractDaysPerWeek AS INT) AS CONTRACT_DAYS_PER_WEEK,
  CAST(eiv.TaxStatus AS STRING) AS TAX_STATUS,
  CAST(eiv.LimitedCompanyName AS STRING) AS LIMITED_COMPANY_NAME,
  CAST(eiv.LimitedCompanyNumber AS STRING) AS LIMITED_COMPANY_NUMBER,
  CAST(eiv.DateAssociatedWithCompanyYear AS INT) AS APPLICANT_COMPANY_ASSOCIATION_START_YEAR,
  CAST(eiv.DateAssociatedWithCompanyMonth AS INT) AS APPLICANT_COMPANY_ASSOCIATION_START_MONTH,
  CAST(eiv.TaxAssessmentMethod AS STRING) AS TAX_ASSESSMENT_METHOD,
  CAST(eiv.AccountantQualification AS STRING) AS ACCOUNTANT_QUALIFICATION,
  CAST(eiv.IsMainEmployment AS TINYINT) AS IS_MAIN_EMPLOYMENT,
  CAST(eiv.ProbationPeriod AS TINYINT) AS IS_IN_PROBATION_PERIOD,
  CAST(eiv.ContractRelatedToApplicant AS TINYINT) AS IS_CONTRACT_RELATED_TO_APPLICANT,
  CAST(eiv.AnyContractGaps AS TINYINT) AS HAS_CONTRACT_GAPS,
  CAST(eiv.EmployedForTaxPurposes AS STRING) AS IS_EMPLOYED_FOR_TAX_PURPOSES,
  CAST(eiv.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
  CAST(eiv.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
  CAST(eiv.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
  CAST(eiv.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
  CAST(eiv.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
  CAST(eiv.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME 
FROM {env_var}_catalog.bronze_mso_con.employment_income_value eiv
WHERE eiv.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1