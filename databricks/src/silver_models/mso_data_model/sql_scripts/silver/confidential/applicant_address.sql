SELECT
  CAST(UPPER(aa.ApplicantAddressId) AS STRING) AS APPLICANT_ADDRESS_ID,
  CAST(UPPER(aa.ApplicantId) AS STRING) AS APPLICANT_ID,
  CAST(aa.AddressType AS STRING) AS ADDRESS_TYPE,
  CAST(UPPER(aa.BuildingName) AS STRING) AS BUILDING_NAME,
  CAST(UPPER(aa.BuildingNo) AS STRING) AS BUILDING_NUMBER,
  CAST(UPPER(aa.Street) AS STRING) AS STREET,
  CAST(UPPER(aa.Line1) AS STRING) AS ADDRESS_LINE_1,
  CAST(UPPER(aa.Line2) AS STRING) AS ADDRESS_LINE_2,
  CAST(UPPER(aa.Line3) AS STRING) AS ADDRESS_LINE_3,
  CAST(UPPER(aa.Line4) AS STRING) AS ADDRESS_LINE_4,
  CAST(UPPER(aa.District) AS STRING) AS DISTRICT,
  CAST(UPPER(aa.Town) AS STRING) AS TOWN,
  CAST(UPPER(aa.County) AS STRING) AS COUNTY,
  CAST(UPPER(aa.Postcode) AS STRING) AS POSTCODE,
  CAST(UPPER(aa.CareOfSurname) AS STRING) AS CARE_OF_SURNAME,
  CAST(aa.CountryTypeCode AS STRING) AS COUNTRY_TYPE_CODE,
  CAST(aa.BfpoNumber AS STRING) AS BRITISH_FORCES_POST_OFFICE_NUMBER,
  CAST(UPPER(aa.OperationName) AS STRING) AS BRITISH_FORCES_OPERATION_NAME,
  CAST(UPPER(aa.ServiceNumber) AS STRING) AS BRITISH_FORCES_SERVICE_NUMBER,
  CAST(UPPER(aa.Rank) AS STRING) AS BRITISH_FORCES_RANK,
  CAST(UPPER(aa.UNIT) AS STRING) AS BRITISH_FORCES_UNIT,
  CAST(aa.MoveInYear AS INT) AS MOVE_IN_YEAR,
  CAST(aa.MoveInMonth AS INT) AS MOVE_IN_MONTH,
  CAST(aa.OccupancyType AS STRING) AS OCCUPANCY_TYPE,
  CAST(aa.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
  CAST(aa.LettingAgent AS TINYINT) AS HAS_LETTING_AGENT,
  CAST(aa.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
  CAST(aa.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
  CAST(aa.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
  CAST(aa.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
  CAST(aa.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME 
FROM {env_var}_catalog.bronze_mso_con.applicant_address aa
WHERE aa.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1