SELECT
  CAST(UPPER(f.FirmId) AS STRING) AS FIRM_ID,
  CAST(f.PrincipalFirmNumber AS BIGINT) AS PRINCIPAL_FIRM_NUMBER,
  CAST(f.RegistrationNumber AS BIGINT) AS FIRM_REGISTRATION_NUMBER,
  CAST(f.AgencyNumber AS STRING) AS AGENCY_NUMBER,
  CAST(UPPER(f.Name) AS STRING) AS FIRM_NAME,
  CAST(UPPER(f.BuildingName) AS STRING) AS BUILDING_NAME,
  CAST(UPPER(f.BuildingNumber) AS STRING) AS BUILDING_NUMBER,
  CAST(UPPER(f.Flat) AS STRING) AS Flat,
  CAST(UPPER(f.Street) AS STRING) AS STREET,
  CAST(UPPER(f.District) AS STRING) AS DISTRICT,
  CAST(UPPER(f.Town) AS STRING) AS TOWN,
  CAST(UPPER(f.County) AS STRING) AS COUNTY,
  CAST(UPPER(f.Postcode) AS STRING) AS POSTCODE,
  CAST(f.FirmType AS STRING) AS FIRM_TYPE,
  CAST(f.EmailAddress AS STRING) AS FIRM_EMAIL_ADDRESS,
  CAST(f.InactiveReason AS STRING) AS INACTIVE_REASON,
  CAST(f.ExternalReference AS STRING) AS EXTERNAL_REFERENCE,
  CAST(f.IsActive AS TINYINT) AS IS_ACTIVE,
  CAST(f.IsSentNotifications AS TINYINT) AS IS_SENT_NOTIFICATIONS,
  CAST(f.CanAdminsAccessAllBrokers AS TINYINT) AS CAN_ADMINS_ACCESS_ALL_BROKERS,
  CAST(f.CreatedDate AS TIMESTAMP) AS CREATED_DATETIME,
  CAST(f.LastUpdatedDate AS TIMESTAMP) AS LAST_UPDATED_DATETIME,
  CAST(f.MDP_ROW_HASH AS STRING) AS MDP_ROW_HASH,
  CAST(f.MDP_LOAD_ID AS BIGINT) AS MDP_LOAD_ID,
  CAST(f.MDP_LOAD_DATETIME AS TIMESTAMP) AS MDP_LOAD_DATETIME,
  CAST(f.__START_AT AS TIMESTAMP) AS ROW_START_DATETIME,
  CAST(f.__END_AT AS TIMESTAMP) AS ROW_END_DATETIME
FROM {env_var}_catalog.bronze_mso_con.firm f
WHERE f.__END_AT IS NULL -- Equivalent of ROW_IS_CURRENT = 1