   CAST(c.CHA_ID AS BIGINT) AS CHANNELS_ID,
   CAST(UPPER(c.DET_ID) AS STRING) AS DATA_ENTITY_TYPES_ID,
   CAST(UPPER(c.TOSUBTYPE_ID) AS STRING) AS TO_SUBTYPE_ID,
   CAST(UPPER(c.FROMSUBTYPE_ID) AS STRING) AS FROM_SUBTYPE_ID,
   CAST(UPPER(c.REPLYSUBTYPE_ID) AS STRING) AS REPLY_SUBTYPE_ID,
   CAST(UPPER(c.CCSUBTYPE_ID) AS STRING) AS CC_SUBTYPE_ID,
   CAST(UPPER(c.BCCSUBTYPE_ID) AS STRING) AS BCC_SUBTYPE_ID,
