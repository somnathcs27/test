   CAST(c.ORDERING AS TINYINT) AS ORDERING,
   CAST(c.MAXITEMS AS INT)  AS MAX_ITEMS,
   CAST(c.VERSION AS INT) AS CHANNELS_VERSION,
   CAST(c.OLDVERSION AS TINYINT) AS OLD_CHANNELS_VERSION,
   CAST(c.DESCRIPTION AS STRING) AS CHANNELS_DESCRIPTION,
   CAST(c.ISCHANNELVIEWERCOLLAPSED AS TINYINT) AS IS_CHANNEL_VIEWER_COLLAPSED,
   CAST(c.ISCHANNELVIEWERSHOWN AS TINYINT) AS IS_CHANNEL_VIEWER_SHOWN,
   CAST(c.CHANNELACTIONS AS STRING) AS CHANNEL_ACTIONS,
