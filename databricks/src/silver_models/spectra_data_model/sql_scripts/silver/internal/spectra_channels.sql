   CAST(c.NAME AS STRING) AS CHANNELS_NAME,
   CAST(c.ISINBOUND AS TINYINT) AS IS_INBOUND,
   CAST(c.ISOUTBOUND AS TINYINT) AS IS_OUTBOUND,
